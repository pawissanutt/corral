#!/usr/bin/env bash
# Regenerate docs/guide/cli.md from `corral <cmd> --help` (recursively).
# Usage: scripts/gen-cli-docs.sh [path-to-corral-binary]
set -euo pipefail
REPO=$(cd "$(dirname "$0")/.." && pwd)
CORRAL=${1:-${CORRAL:-$REPO/target/debug/corral}}
OUT=$REPO/docs/guide/cli.md
[ -x "$CORRAL" ] || { echo "corral binary not found: $CORRAL (cargo build -p corral)" >&2; exit 1; }
mkdir -p "$(dirname "$OUT")"

subcommands() {
  awk '/^Commands:/{on=1; next} on && /^[^ ]/{on=0} on && /^  [a-z]/{print $1}' | grep -vx help || true
}

help_of() { "$CORRAL" "$@" --help </dev/null 2>&1; }

emit() {
  local depth=$1; shift
  local hashes; hashes=$(printf '#%.0s' $(seq $((depth + 2))))
  echo "$hashes \`corral $*\`"
  echo
  echo '```text'
  help_of "$@"
  echo '```'
  echo
  local sub
  for sub in $(help_of "$@" | subcommands); do
    emit $((depth + 1)) "$@" "$sub"
  done
}

{
  echo '# CLI reference'
  echo
  echo '<!-- Generated by scripts/gen-cli-docs.sh from `corral <cmd> --help`. Do not edit by hand. -->'
  echo
  echo "Generated from \`corral $("$CORRAL" --version </dev/null | awk '{print $2}')\`. Every command also accepts"
  echo '`--root <ROOT>` (the directory containing `.corral/`; default: discovered from the current directory).'
  echo
  echo '```text'
  help_of
  echo '```'
  echo
  for cmd in $(help_of | subcommands); do
    emit 0 "$cmd"
  done
} > "$OUT"
echo "wrote $OUT"
