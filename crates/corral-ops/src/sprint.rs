//! Deterministic sprint readback. No provider, transcript, usage refresh, or live pane access.
use std::collections::BTreeMap;
use std::io::Write;

use anyhow::{Context, Result};
use corral_core::{Artifact, ArtifactKind, Event, Origin, PinRef, Run, Status, Task};
use jiff::Timestamp;
use serde::Serialize;
use serde_json::{Value, json};

use crate::Ctx;

#[path = "sprint_markdown.rs"]
mod markdown;

#[derive(Debug, Clone, Serialize)]
pub struct SprintReview {
    pub since: Option<Timestamp>,
    pub snapshot_at: Timestamp,
    pub marked: bool,
    pub sections: SprintSections,
    pub artifact: Artifact,
    pub artifact_ref: String,
    pub markdown: String,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize)]
pub struct SprintSections {
    pub landed: Vec<SprintChange>,
    pub sent_back_failed: Vec<SprintChange>,
    pub dropped_rejected_escalated: Vec<SprintChange>,
    pub in_flight: Vec<SprintTask>,
    pub owner_ideas: Vec<SprintTask>,
    pub decisions: Vec<SprintDecision>,
    pub numbers: SprintNumbers,
}

#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct SprintChange {
    pub task: Option<String>,
    pub title: Option<String>,
    pub at: Timestamp,
    pub kind: String,
    pub run: Option<String>,
    pub summary: Option<String>,
    pub sha: Option<String>,
    pub verdict: Option<String>,
    pub demos: Vec<String>,
    pub reason: Option<String>,
    pub resolution: Option<String>,
    pub action: Option<String>,
    pub actor: Option<String>,
    pub into: Option<String>,
    pub owner_origin: bool,
    /// Approval of this reduction, not an inference from unrelated owner comments.
    pub owner_ok: Option<bool>,
    pub needs_owner_ok: bool,
    pub detail: Value,
}

#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct SprintTask {
    pub task: String,
    pub path: String,
    pub title: String,
    pub status: Status,
    pub stage: Option<String>,
    pub progress: Option<corral_core::RunProgress>,
    pub wait_reason: Option<String>,
    pub depends_on: Vec<String>,
    pub links: Vec<String>,
    pub disposition: Option<corral_core::IdeaDecision>,
    pub decisions: Vec<Event>,
}

#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct SprintDecision {
    pub task: String,
    pub question: String,
    pub requested_action: Option<String>,
    /// Only a recorded recommendation; never generated by the report.
    pub pm_recommendation: Option<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize)]
pub struct SprintNumbers {
    pub by_task: BTreeMap<String, SprintTotals>,
    pub by_profile: BTreeMap<String, SprintTotals>,
    pub review_rounds: usize,
    pub gate_failures: usize,
    pub lessons: Vec<Event>,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize)]
pub struct SprintTotals {
    pub runs: usize,
    pub reported_usd: Option<f64>,
    pub estimated_usd: Option<f64>,
    pub unknown_cost_runs: usize,
    pub wall_seconds: Option<i64>,
}

/// Builds and pins a Report artifact, then optionally advances the sprint watermark.
///
/// The mark stores the collection cutoff, not the later artifact/pin completion time.
/// Reports serialize against each other; task/event producers remain independent.
/// An empty workspace gets one Done task named "Sprint review reports" as its anchor.
/// Subsequent reports reuse the first existing task, never create a task per report.
pub fn review_sprint(ctx: &Ctx, since: Option<&str>, mark: bool) -> Result<SprintReview> {
    let _lock = ctx
        .store
        .try_lock("sprint-review")?
        .context("another sprint review is in progress")?;
    let snapshot_at = Timestamp::now();
    let events = ctx.store.events()?;
    let since = match since {
        None | Some("last") => events
            .iter()
            .rev()
            .find(|e| e.kind == "sprint_review_mark" && e.ts <= snapshot_at)
            .map(|event| {
                event.detail["snapshot_at"]
                    .as_str()
                    .map(|s| s.parse::<Timestamp>().context("invalid sprint review mark"))
                    .unwrap_or(Ok(event.ts))
            })
            .transpose()?,
        Some(s) => Some(
            s.parse::<Timestamp>()
                .context("since must be RFC3339 or last")?,
        ),
    };
    anyhow::ensure!(
        since.is_none_or(|s| s <= snapshot_at),
        "since is after the sprint snapshot"
    );
    let tasks = ctx.store.list()?;
    let sections = collect_sprint_review(&tasks, &events, since, snapshot_at);
    let markdown = markdown::render(&sections, since, snapshot_at)?;
    let anchor = match tasks.iter().min_by_key(|t| &t.id) {
        Some(task) => task.id.clone(),
        None => {
            ctx.store
                .create(
                    "Sprint review reports",
                    None,
                    Status::Done,
                    "Stable artifact anchor for sprint reports in an initially empty workspace.",
                )?
                .id
        }
    };
    let scratch = tempfile::tempdir().context("creating sprint report scratch directory")?;
    let path = scratch.path().join("sprint-review.md");
    let mut file = std::fs::File::create(&path).context("creating sprint report markdown")?;
    file.write_all(markdown.as_bytes())
        .context("writing sprint report markdown")?;
    let artifact = crate::add_artifact(
        ctx,
        &anchor,
        &path,
        Some(ArtifactKind::Report),
        Some("Sprint review"),
    )?;
    let artifact_ref = PinRef::of_artifact(&anchor, &artifact).to_string();
    ctx.store.pin(&artifact_ref, Some("Sprint review"), false)?;
    if mark {
        ctx.store.log_event(
            Some(&anchor),
            "sprint_review_mark",
            json!({"snapshot_at": snapshot_at, "since": since, "artifact": artifact_ref}),
        )?;
    }
    Ok(SprintReview {
        since,
        snapshot_at,
        marked: mark,
        sections,
        artifact,
        artifact_ref,
        markdown,
    })
}

/// Pure collection seam. Historical sections and run accounting use `(since, snapshot_at]`.
/// Run costs are recorded cumulative values for runs ending in the window (or starting
/// there when unfinished), not estimated deltas. Reviewer children count under their profiles.
/// Snapshot sections deliberately survive an otherwise empty event window.
pub fn collect_sprint_review(
    tasks: &[Task],
    events: &[Event],
    since: Option<Timestamp>,
    snapshot_at: Timestamp,
) -> SprintSections {
    let mut result = SprintSections::default();
    let mut tasks: Vec<_> = tasks.iter().collect();
    tasks.sort_by_key(|t| &t.id);
    let mut history: Vec<_> = events.iter().filter(|e| e.ts <= snapshot_at).collect();
    // Stable sort retains append order for events at exactly the same timestamp.
    history.sort_by_key(|e| e.ts);
    let window: Vec<_> = history
        .iter()
        .copied()
        .filter(|e| since.is_none_or(|s| e.ts > s))
        .collect();
    for event in &window {
        let audited_drop = !event.detail["task_updated"].is_null()
            && window.iter().any(|audit| {
                audit.task == event.task
                    && audit.kind == "idea_decided"
                    && audit.detail["task_updated"] == event.detail["task_updated"]
                    && matches!(
                        audit.detail["action"].as_str(),
                        Some("drop" | "decline" | "merge")
                    )
            });
        let task = tasks
            .iter()
            .copied()
            .find(|t| event.task.as_deref() == Some(&t.id));
        let row = change(event, task, &window, snapshot_at);
        let kind = effective_kind(event);
        match kind {
            "approved" if event.detail["strategy"] != "keep_branch" => result.landed.push(row),
            "changes_requested" | "changes" | "failed" | "abandoned" => {
                result.sent_back_failed.push(row);
            }
            "discarded" => {
                result.sent_back_failed.push(row.clone());
                if !audited_drop {
                    result.dropped_rejected_escalated.push(row);
                }
            }
            "verdict" if event.detail["verdict"] == "changes" => {
                result.sent_back_failed.push(row);
            }
            "gate" if event.detail["result"] == "fail" => result.sent_back_failed.push(row),
            "idea_decided"
                if matches!(
                    row.action.as_deref(),
                    Some("drop" | "decline" | "defer" | "narrow" | "merge")
                ) =>
            {
                result.dropped_rejected_escalated.push(row);
            }
            "dropped" | "rejected" | "escalated" => result.dropped_rejected_escalated.push(row),
            "moved" if event.detail["to"] == "dropped" && !audited_drop => {
                result.dropped_rejected_escalated.push(row);
            }
            "verdict" if event.detail["verdict"] == "escalate" => {
                result.dropped_rejected_escalated.push(row);
            }
            _ => {}
        }
    }
    result.dropped_rejected_escalated.sort_by(|a, b| {
        b.owner_origin
            .cmp(&a.owner_origin)
            .then_with(|| a.at.cmp(&b.at))
            .then_with(|| a.task.cmp(&b.task))
    });
    for task in &tasks {
        let snapshot = task_snapshot(task, &tasks, &history, snapshot_at);
        match task.status {
            Status::Ready | Status::Running | Status::NeedsMe | Status::Review => {
                result.in_flight.push(snapshot.clone());
            }
            Status::Idea | Status::Backlog | Status::Done | Status::Dropped => {}
        }
        if task.effective_origin() == Origin::Owner {
            result.owner_ideas.push(snapshot);
        }
        let recommendation = history.iter().rev().find_map(|e| {
            (e.task.as_deref() == Some(&task.id))
                .then(|| text(&e.detail, &["pm_recommendation", "recommendation"]))
                .flatten()
        });
        if let Some(run) = task.current_run() {
            for decision in run.obligations.decisions.iter().filter(|d| d.pending()) {
                result.decisions.push(SprintDecision {
                    task: task.id.clone(),
                    question: decision.request.question.clone(),
                    requested_action: Some(decision.request.requested_action.clone()),
                    pm_recommendation: recommendation.clone(),
                });
            }
            if task.status == Status::NeedsMe && run.obligations.pending_decision().is_none() {
                result.decisions.push(SprintDecision {
                    task: task.id.clone(),
                    question: corral_core::CardField::NeedsMe
                        .text(task, &[], snapshot_at, false)
                        .unwrap_or_else(|| "Owner input required; question not recorded".into()),
                    requested_action: None,
                    pm_recommendation: recommendation,
                });
            }
        }
        for run in &task.runs {
            account_run(&mut result.numbers, &task.id, run, since, snapshot_at);
        }
    }
    // Legacy change requests have no run field. Attribute them by dispatch interval,
    // and avoid counting a verdict and its change request as two review rounds.
    let mut rounds: BTreeMap<_, (usize, usize)> = BTreeMap::new();
    for event in &window {
        if matches!(
            event.kind.as_str(),
            "verdict" | "changes_requested" | "approved"
        ) {
            let task = tasks.iter().find(|t| event.task.as_deref() == Some(&t.id));
            let run = task
                .and_then(|t| event_run(t, event))
                .map(|r| r.id.clone())
                .or_else(|| text(&event.detail, &["run"]));
            let counts = rounds.entry((event.task.clone(), run)).or_default();
            if event.kind == "verdict" {
                counts.0 += 1;
            } else {
                counts.1 += 1;
            }
        }
    }
    result.numbers.review_rounds = rounds
        .values()
        .map(|(verdicts, fallback)| (*verdicts).max(*fallback))
        .sum();
    result.numbers.gate_failures = window
        .iter()
        .filter(|e| e.kind == "gate" && e.detail["result"] == "fail")
        .count();
    result.numbers.lessons = window
        .iter()
        .filter(|e| {
            matches!(
                e.kind.as_str(),
                "lessons_applied"
                    | "lesson_added"
                    | "lesson_updated"
                    | "lessons_distilled"
                    | "lessons_due"
            )
        })
        .map(|e| (*e).clone())
        .collect();
    result
}

fn effective_kind(event: &Event) -> &str {
    if event.kind == "autopilot" {
        event.detail["to"].as_str().unwrap_or(&event.kind)
    } else {
        &event.kind
    }
}

fn text(detail: &Value, keys: &[&str]) -> Option<String> {
    keys.iter()
        .find_map(|key| detail[*key].as_str().map(str::to_owned))
}

fn event_run<'a>(task: &'a Task, event: &Event) -> Option<&'a Run> {
    match event.detail["run"].as_str() {
        Some(id) => task.runs.iter().find(|r| r.id == id),
        None => task
            .runs
            .iter()
            .filter(|r| r.started <= event.ts)
            .max_by_key(|r| r.started),
    }
}

fn change(
    event: &Event,
    task: Option<&Task>,
    window: &[&Event],
    cutoff: Timestamp,
) -> SprintChange {
    let run = task.and_then(|t| event_run(t, event));
    let owner_origin = task.is_some_and(|t| t.effective_origin() == Origin::Owner);
    let action = text(&event.detail, &["action"]).or_else(|| {
        (matches!(effective_kind(event), "dropped" | "discarded" | "rejected")
            || event.detail["to"] == "dropped")
            .then(|| "drop".into())
    });
    let reduction = matches!(
        action.as_deref(),
        Some("drop" | "decline" | "defer" | "narrow" | "merge")
    ) || matches!(effective_kind(event), "rejected" | "escalated")
        || event.detail["verdict"] == "escalate";
    let owner_ok = event.detail["owner_ok"].as_bool();
    let demos = task
        .map(|t| {
            t.artifacts
                .iter()
                .filter(|a| {
                    a.added <= cutoff
                        && a.purged_at.is_none()
                        && run.is_none_or(|r| r.id == a.run)
                        && matches!(
                            a.kind,
                            ArtifactKind::Report
                                | ArtifactKind::Screenshot
                                | ArtifactKind::Evidence
                        )
                        && a.title != "Sprint review"
                })
                .map(|a| PinRef::of_artifact(&t.id, a).to_string())
                .collect()
        })
        .unwrap_or_default();
    let resolution = window
        .iter()
        .rev()
        .find(|e| {
            e.ts > event.ts
                && e.task == event.task
                && matches!(
                    effective_kind(e),
                    "approved" | "done" | "dispatched" | "superseded" | "discarded"
                )
                && (event.detail["run"].is_null()
                    || e.detail["run"].is_null()
                    || e.detail["run"] == event.detail["run"]
                    || e.kind == "superseded")
        })
        .map(|e| effective_kind(e).to_owned());
    SprintChange {
        task: event.task.clone(),
        title: task.map(|t| t.title.clone()),
        at: event.ts,
        kind: effective_kind(event).into(),
        run: run
            .map(|r| r.id.clone())
            .or_else(|| text(&event.detail, &["run"])),
        summary: text(&event.detail, &["summary"])
            .or_else(|| run.and_then(|r| r.summary.clone()))
            .and_then(|summary| {
                summary
                    .lines()
                    .find(|line| !line.trim().is_empty())
                    .map(|line| line.trim().to_string())
            }),
        sha: text(&event.detail, &["sha"]),
        verdict: text(&event.detail, &["verdict"]).or_else(|| {
            run.and_then(|r| r.review.as_ref())
                .filter(|r| r.at <= cutoff)
                .and_then(|r| r.verdict)
                .map(|v| v.as_str().to_owned())
        }),
        demos,
        reason: text(
            &event.detail,
            &["reason", "text", "notes", "failed_cmd", "error"],
        )
        .or_else(|| {
            run.and_then(|r| r.review.as_ref())
                .filter(|review| review.at <= cutoff)
                .filter(|review| {
                    event.detail["verdict"].as_str().is_none_or(|verdict| {
                        review
                            .verdict
                            .is_some_and(|current| current.as_str() == verdict)
                    })
                })
                .and_then(|review| review.notes.clone())
        }),
        resolution,
        action,
        actor: text(&event.detail, &["actor", "by", "reviewer"])
            .or_else(|| (event.kind == "autopilot").then(|| "autopilot".into())),
        into: text(&event.detail, &["into"]),
        owner_origin,
        owner_ok,
        needs_owner_ok: owner_origin && reduction && owner_ok != Some(true),
        detail: event.detail.clone(),
    }
}

fn task_snapshot(task: &Task, tasks: &[&Task], history: &[&Event], at: Timestamp) -> SprintTask {
    let run = task.current_run();
    let mut links = task.depends_on.clone();
    if let Some(into) = task.idea_decision.as_ref().and_then(|d| d.into.as_ref()) {
        links.push(into.clone());
    }
    let decisions: Vec<_> = history
        .iter()
        .filter(|e| {
            (e.task.as_deref() == Some(&task.id) || e.detail["into"] == task.id)
                && matches!(e.kind.as_str(), "idea_decided" | "owner_decision")
        })
        .map(|e| (*e).clone())
        .collect();
    for event in &decisions {
        if let Some(into) = event.detail["into"].as_str() {
            links.push(into.into());
        }
        if let Some(from) = &event.task
            && from != &task.id
        {
            links.push(from.clone());
        }
    }
    links.extend(
        task.artifacts
            .iter()
            .filter(|a| a.added <= at && a.purged_at.is_none() && a.title != "Sprint review")
            .map(|a| PinRef::of_artifact(&task.id, a).to_string()),
    );
    links.sort();
    links.dedup();
    let wait_reason = if task.status == Status::Ready {
        let deps: Vec<_> = task
            .depends_on
            .iter()
            .filter(|id| {
                !tasks
                    .iter()
                    .any(|t| &t.id == *id && t.status == Status::Done)
            })
            .cloned()
            .collect();
        if !deps.is_empty() {
            Some(format!("dependencies: {}", deps.join(", ")))
        } else if task.dispatch_hold {
            Some("dispatch hold".into())
        } else {
            history
                .iter()
                .rev()
                .find_map(|e| {
                    (e.task.as_deref() == Some(&task.id) && e.kind == "queued")
                        .then(|| text(&e.detail, &["reason"]))
                        .flatten()
                })
                .or_else(|| {
                    Some(
                        if task.queued {
                            "queued; wait reason not recorded"
                        } else {
                            "not queued"
                        }
                        .into(),
                    )
                })
        }
    } else {
        run.and_then(|r| r.obligations.waits.iter().find(|w| w.receipt.is_none()))
            .map(|w| w.request.condition.clone())
            .or_else(|| run.and_then(|r| r.blocked_excerpt.clone()))
    };
    SprintTask {
        task: task.id.clone(),
        path: task.path.display().to_string(),
        title: task.title.clone(),
        status: task.status,
        stage: run
            .and_then(|r| r.autopilot.as_ref())
            .map(|a| a.stage.as_str().into())
            .or_else(|| run.and_then(|r| r.agent_state.clone())),
        progress: run.and_then(|r| r.progress.clone()),
        wait_reason,
        depends_on: task.depends_on.clone(),
        links,
        disposition: task.idea_decision.clone(),
        decisions,
    }
}

pub(crate) fn account_run(
    numbers: &mut SprintNumbers,
    task: &str,
    run: &Run,
    since: Option<Timestamp>,
    at: Timestamp,
) {
    let recorded_at = run.ended.unwrap_or(run.started);
    if recorded_at <= at && since.is_none_or(|s| recorded_at > s) {
        // Children are accounted separately below, avoiding double-counted review costs.
        let reported = run
            .usage
            .as_ref()
            .and_then(|u| u.reported_usd.or(u.cost_usd));
        let estimated = run.usage.as_ref().and_then(|u| u.estimated_usd);
        let seconds = run
            .ended
            .filter(|end| *end >= run.started)
            .map(|end| end.as_second() - run.started.as_second());
        for total in [
            numbers.by_task.entry(task.into()).or_default(),
            numbers
                .by_profile
                .entry(run.profile.as_deref().unwrap_or(&run.agent).into())
                .or_default(),
        ] {
            total.runs += 1;
            if let Some(cost) = reported {
                *total.reported_usd.get_or_insert(0.0) += cost;
            }
            if let Some(cost) = estimated {
                *total.estimated_usd.get_or_insert(0.0) += cost;
            }
            total.unknown_cost_runs += usize::from(reported.is_none() && estimated.is_none());
            if let Some(seconds) = seconds {
                *total.wall_seconds.get_or_insert(0) += seconds;
            }
        }
    }
    for child in &run.review_runs {
        account_run(numbers, task, child, since, at);
    }
}
