    /// Reads and parses a corral.toml.
    pub fn load(path: &Path) -> Result<Config> {
        let text =
            std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
        toml::from_str(&text).with_context(|| format!("parsing {}", path.display()))
    }

    /// Default config for a workspace root: every immediate subdirectory of `root` that contains a
    /// `.git` entry becomes a project (key = dir name, path = dir name); if `root` itself is a git
    /// repo with no such children, it becomes project "<root dir name>" with path ".".
    /// Default harnesses (exact strings), each with a same-named profile (no model/effort):
    ///   omo     = omo -n '{name}' {model_args} {prompt_ref}
    ///   omp     = omp {model_args} {prompt_ref}
    ///   claude  = claude {model_args} {prompt_ref}
    ///   generic = cat '{prompt_file}'   (shows the prompt; a human or any agent takes it from there)
    pub fn default_for(root: &Path) -> Config {
        let mut projects = BTreeMap::new();
        if let Ok(rd) = std::fs::read_dir(root) {
            for entry in rd.flatten() {
                let p = entry.path();
                if p.is_dir() && p.join(".git").exists() {
                    let name = entry.file_name().to_string_lossy().into_owned();
                    if name.starts_with('.') {
                        continue;
                    }
                    projects.insert(
                        name.clone(),
                        Project {
                            dispatch: DispatchOverride::default(),
                            artifact_retention: None,
                            post_land: Vec::new(),
                            path: name,
                            default_profile: None,
                            base: None,
                            review: ReviewOverride::default(),
                        },
                    );
                }
            }
        }
        if projects.is_empty() && root.join(".git").exists() {
            let name = root
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
                .unwrap_or_else(|| "root".to_string());
            projects.insert(
                name,
                Project {
                    dispatch: DispatchOverride::default(),
                    artifact_retention: None,
                    post_land: Vec::new(),
                    path: ".".into(),
                    default_profile: None,
                    base: None,
                    review: ReviewOverride::default(),
                },
            );
        }
        let mut harnesses = BTreeMap::new();
        let mut profiles = BTreeMap::new();
        for (k, v) in [
            ("omo", "omo -n '{name}' {model_args} {prompt_ref}"),
            ("omp", "omp {model_args} {prompt_ref}"),
            ("claude", "claude {model_args} {prompt_ref}"),
            ("generic", "cat '{prompt_file}'"),
        ] {
            harnesses.insert(
                k.to_string(),
                Harness {
                    command: v.to_string(),
                    flags: None,
                    model_flag: None,
                    effort_flag: None,
                    efforts: Vec::new(),
                    prompt: None,
                },
            );
            profiles.insert(
                k.to_string(),
                Profile {
                    metadata: None,
                    harness: k.to_string(),
                    model: None,
                    vendor: None,
                    escalate_to: None,
                    effort: None,
                    args: Vec::new(),
                },
            );
        }
        Config {
            automation: crate::OperatingPolicy::default(),
            pricing: BTreeMap::new(),
            limits: Limits::default(),
            resources: crate::ResourcesCfg::default(),
            dispatch: DispatchCfg::default(),
            projects,
            defaults: Defaults::default(),
            routing: crate::Routing::default(),
            harnesses,
            profiles,
            agents: BTreeMap::new(),
            artifacts: ArtifactCfg::default(),
            herdr: HerdrCfg::default(),
            pm: PmCfg::default(),
            agent: AgentCfg::default(),
            lessons: LessonsCfg::default(),
            digest: DigestCfg::default(),
            review: ReviewOverride::default(),
            sync: SyncCfg::default(),
            ui: UiCfg::default(),
            board: crate::BoardCfg::default(),
            viewers: BTreeMap::new(),
        }
    }

    /// Serializes to TOML (round-trips through `load`).
    pub fn to_toml(&self) -> String {
        toml::to_string_pretty(self).unwrap_or_default()
    }

    /// Effective values for reads and edit deltas, including arrays omitted by pretty serialization.
    pub fn effective_value(&self) -> Result<toml::Value> {
        let mut value = toml::Value::try_from(self).context("encoding effective config")?;
        for (section, field) in [
            ("profiles", "args"),
            ("harnesses", "efforts"),
            ("projects", "post_land"),
            ("pricing", "aliases"),
        ] {
            if let Some(entries) = value.get_mut(section).and_then(toml::Value::as_table_mut) {
                for (_, entry) in entries.iter_mut() {
                    entry
                        .as_table_mut()
                        .context("config entry is not a table")?
                        .entry(field)
                        .or_insert_with(|| toml::Value::Array(Vec::new()));
                }
            }
        }
        let mut board = toml::Value::try_from(&self.board).context("encoding board")?;
        board
            .get_mut("card")
            .and_then(toml::Value::as_table_mut)
            .context("board.card is not a table")?
            .insert(
                "columns".into(),
                toml::Value::try_from(&self.board.card.columns).context("encoding columns")?,
            );
        let mut routing = toml::Value::try_from(&self.routing).context("encoding routing")?;
        if let Some(rules) = routing.get_mut("rules").and_then(toml::Value::as_array_mut) {
            for rule in rules {
                let rule = rule.as_table_mut().context("routing rule is not a table")?;
                for field in ["project", "kind", "size"] {
                    rule.entry(field)
                        .or_insert_with(|| toml::Value::Array(Vec::new()));
                }
            }
        }
        let table = value.as_table_mut().context("config is not a table")?;
        table.insert(
            "automation".into(),
            toml::Value::try_from(&self.automation)
                .context("encoding effective operating policy")?,
        );
        table.insert("board".into(), board);
        table.insert("routing".into(), routing);
        let review = table
            .entry("review")
            .or_insert_with(|| toml::Value::Table(Default::default()))
            .as_table_mut()
            .context("review is not a table")?;
        review
            .entry("require_cross_family")
            .or_insert(toml::Value::Boolean(false));
        let policy = self.review_policy(None, None);
        for (key, session) in [
            ("worker_session", policy.worker_session),
            ("reviewer_session", policy.reviewer_session),
        ] {
            review.insert(
                key.into(),
                toml::Value::try_from(session).context("encoding session policy")?,
            );
        }
        Ok(value)
    }

    /// Checks the config against the workspace at `root` and reports every problem: limits must be > 0,
    /// per-project limits must name projects, project paths must be directories, profile/harness/reviewer
    /// references must resolve, profile model/effort must suit the harness, globs must parse.
    pub fn validate(&self, root: &Path) -> std::result::Result<(), ConfigErrors> {
        let mut problems = self.problems(root, &SemanticInputs::default());
        problems.extend(
            self.profile_problems()
                .into_iter()
                .map(|problem| format!("{}: {}", problem.key.join("."), problem.message)),
        );
        if problems.is_empty() {
            Ok(())
        } else {
            Err(ConfigErrors(problems))
        }
    }

    pub(crate) fn problems(&self, root: &Path, inputs: &SemanticInputs) -> Vec<String> {
        let mut out = self.board.card.problems();
        out.extend(attention::problems(&self.pm));
        if let Some(policy) = &self.routing.repair
            && let Err(error) = policy.validate()
        {
            out.push(format!("routing.repair: {error:#}"));
        }
        out.extend(self.ui.problems());
        out.extend(self.resources.problems());
        if self.limits.running == 0 {
            out.push("limits.running must be > 0".to_string());
        }
        if self.sync.startup_grace_secs == 0 {
            out.push("sync.startup_grace_secs must be > 0".to_string());
        }
        if self.sync.review_idle_after_secs == 0 {
            out.push("sync.review_idle_after_secs must be > 0".to_string());
        }
        if !(30..=3600).contains(&self.review_infra_wait_secs()) {
            out.push("review.infra_wait_secs must be within 30..=3600".into());
        }
        if self.limits.review == 0 {
            out.push("limits.review must be > 0".to_string());
        }
        if self.dispatch.max_auto_promotions_per_day == 0 {
            out.push("dispatch.max_auto_promotions_per_day must be > 0".to_string());
        }
        for project in &self.dispatch.ready_projects {
            if !self.projects.contains_key(project) {
                out.push(format!(
                    "dispatch.ready_projects: unknown project '{project}'"
                ));
            }
        }
        for (k, n) in &self.limits.per_project {
            if !self.projects.contains_key(k) {
                out.push(format!("limits.per_project.{k}: unknown project '{k}'"));
            }
            if *n == 0 {
                out.push(format!("limits.per_project.{k} must be > 0"));
            }
        }
        let mut profiles = self.profile_names();
        profiles.extend_from_slice(&inputs.rejected_profiles);
        let check_profile = |out: &mut Vec<String>, key: String, name: &str| {
            if inputs.profiles_complete() && !profiles.iter().any(|p| p == name) {
                out.push(format!(
                    "{key}: unknown profile '{name}' (configured: {})",
                    profiles.join(", ")
                ));
            }
        };
        if let Some(name) = &self.lessons.profile {
            check_profile(&mut out, "lessons.profile".into(), name);
        }
        if let Some(every) = &self.lessons.every
            && let Err(error) = parse_age(every)
        {
            out.push(format!("lessons.every: {error:#}"));
        }
        if let Some(every) = &self.digest.every
            && let Err(error) = parse_age(every)
        {
            out.push(format!("digest.every: {error:#}"));
        }
        for (name, threshold) in [
            ("after_landings", self.lessons.after_landings),
            ("after_failures", self.lessons.after_failures),
        ] {
            if threshold == Some(0) {
                out.push(format!("lessons.{name} must be > 0"));
            }
        }
        for (name, secs) in [
            (
                "question_unattended_secs",
                self.agent.question_unattended_secs,
            ),
            (
                "gate_start_uncertain_secs",
                self.agent.gate_start_uncertain_secs,
            ),
            ("drain_secs", self.agent.drain_secs),
        ] {
            if secs == 0 {
                out.push(format!("agent.{name} must be > 0"));
            }
        }
        if !(1..=20).contains(&self.lessons.top) {
            out.push("lessons.top must be within 1..=20".into());
        }
        for (k, p) in &self.projects {
            if let Some(secs) = p.review.infra_wait_secs
                && !(30..=3600).contains(&secs)
            {
                out.push(format!(
                    "projects.{k}.review.infra_wait_secs must be within 30..=3600"
                ));
            }
            if p.dispatch.max_auto_promotions_per_day == Some(0) {
                out.push(format!(
                    "projects.{k}.dispatch.max_auto_promotions_per_day must be > 0"
                ));
            }
            if let Some(retention) = &p.artifact_retention {
                out.extend(retention.problems(&format!("projects.{k}.artifacts.retention")));
            }
            out.extend(crate::hooks::problems(k, &p.post_land));
            let path = Path::new(&p.path);
            if p.path.trim().is_empty() {
                out.push(format!("projects.{k}.path is empty"));
            } else if !root.join(path).is_dir() {
                out.push(format!(
                    "projects.{k}.path: {} is not a directory",
                    root.join(path).display()
                ));
            }
            if let Some(name) = &p.default_profile {
                check_profile(&mut out, format!("projects.{k}.default_profile"), name);
            }
        }
        if let Some(name) = &self.defaults.profile {
            check_profile(&mut out, "defaults.profile".into(), name);
        }
        check_profile(&mut out, "pm.agent".into(), &self.pm.agent);
        for kind in &self.pm.push_kinds {
            if !PM_ACTIONABLE_KINDS.contains(&kind.as_str()) {
                out.push(format!(
                    "pm.push_kinds: unknown actionable kind {kind:?}; use {}",
                    PM_ACTIONABLE_KINDS.join(", ")
                ));
            }
        }
        // Layered validation already checked these supplied fields with structured paths.
        // Re-emitting their display strings would lose literal dynamic-name identity.
        if !inputs.independent_checked {
            for (k, h) in &self.harnesses {
                if h.command.trim().is_empty() {
                    out.push(format!("harnesses.{k}.command is empty"));
                }
                if let Err(e) = h.flag_map(k) {
                    out.push(format!("harnesses.{k}.flags: {e:#}"));
                }
            }
            for (k, a) in &self.agents {
                if a.command.trim().is_empty() {
                    out.push(format!("agents.{k}.command is empty"));
                }
            }
            let targets = self
                .profiles
                .iter()
                .filter_map(|(name, profile)| Some((name.clone(), profile.escalate_to.clone()?)))
                .collect();
            out.extend(
                escalation_problems(
                    &profiles.into_iter().collect(),
                    &targets,
                    inputs.profiles_complete(),
                )
                .into_iter()
                .map(|problem| format!("{}: {}", problem.key.join("."), problem.message)),
            );
        }
        for glob in &self.artifacts.globs {
            if let Err(e) = validate_glob(glob) {
                out.push(format!("artifacts.globs: {e:#}"));
            }
        }
        if self.artifacts.max_bytes == 0 {
            out.push("artifacts.max_bytes must be > 0".to_string());
        }
        out.extend(self.artifacts.retention.problems("artifacts.retention"));
        for (key, value) in [
            ("max_total", &self.artifacts.max_total),
            ("max_file", &self.artifacts.max_file),
        ] {
            if let Err(e) = crate::parse_bytes(value) {
                out.push(format!("artifacts.{key}: {e:#}"));
            }
        }
        if let Err(e) = parse_age(&self.ui.done_window) {
            out.push(format!("ui.done_window: {e:#}"));
        }
        out.extend(self.review_problems_with_inputs(inputs));
        out.extend(self.pricing_problems());
        out
    }
